import { FONT_PAIRINGS } from "./font-pairings.ts";

// A strict reader for exactly the CSS the brand emitter may produce, used by the tests: any line
// outside this grammar is an error, so nothing but the expected custom properties can hide in it.

export interface EmittedBlock {
  /** The enclosing at-rules, outermost first. */
  readonly context: readonly string[];
  readonly selectors: readonly string[];
  readonly declarations: readonly (readonly [string, string])[];
}

const HEADER = "/* Generated by @identgineer/tokens. Do not edit. */";
const LAYERS =
  "@layer idg.tokens, idg.theme, idg.design, idg.layout, idg.ux, idg.brand, idg.preferences;";
const AT_RULES = [
  "@layer idg.theme {",
  "@layer idg.brand {",
  "@media (prefers-color-scheme: dark) {",
];
const HEX = "#[0-9a-f]{6}";
const FAMILIES = new Set(
  FONT_PAIRINGS.flatMap((pairing) => [...pairing.display, ...pairing.body, ...pairing.mono]),
);

function isFontList(value: string): boolean {
  return value.split(", ").every((entry) => {
    const quoted = /^"([A-Za-z0-9 -]+)"$/.exec(entry);
    const name = quoted ? quoted[1] : /^[A-Za-z0-9-]+$/.test(entry) ? entry : undefined;
    return name !== undefined && FAMILIES.has(name) && (quoted !== null) === name.includes(" ");
  });
}

const VALUE_RULES: readonly (readonly [RegExp, (value: string) => boolean])[] = [
  [/^color-scheme$/, (value) => value === "light" || value === "dark"],
  [/^--idg-color-[a-z]+(?:-[a-z]+)*$/, (value) => new RegExp(`^${HEX}$`).test(value)],
  [
    /^--idg-gradient-brand$/,
    (value) => new RegExp(`^linear-gradient\\(135deg, ${HEX} 0%, ${HEX} 100%\\)$`).test(value),
  ],
  [/^--idg-font-family-(display|body|mono)$/, isFontList],
  [/^--idg-font-display-weight$/, (value) => /^[4-9]00$/.test(value)],
  [/^--idg-font-(display|body)-letter-spacing$/, (value) => /^-?0(\.\d{1,3})?em$/.test(value)],
  [/^--idg-font-(display|body)-line-height$/, (value) => /^1(\.\d{1,2})?$/.test(value)],
  [/^--idg-shape-radius-(sm|md|lg|pill)$/, (value) => /^(\d+(\.\d{1,3})?rem|9999px)$/.test(value)],
];

function checkDeclaration(name: string, value: string, where: string): void {
  const rule = VALUE_RULES.find(([pattern]) => pattern.test(name));
  if (!rule) throw new Error(`${where}: unexpected property ${JSON.stringify(name)}`);
  if (!rule[1](value))
    throw new Error(`${where}: unexpected value ${JSON.stringify(value)} for ${name}`);
}

/** Reads emitted CSS into blocks, or throws naming the first line outside the grammar. */
export function readEmittedCss(css: string, allowedSelectors: readonly string[]): EmittedBlock[] {
  const lines = css.split("\n");
  if (lines[0] !== HEADER || lines[1] !== LAYERS || lines[2] !== "" || lines.at(-1) !== "") {
    throw new Error("the header, layer order or final newline is not as emitted");
  }
  const blocks: EmittedBlock[] = [];
  const context: string[] = [];
  let selectors: string[] = [];
  let declarations: [string, string][] | undefined;
  for (const [index, line] of lines.slice(3, -1).entries()) {
    const where = `line ${String(index + 4)}`;
    const indent = "  ".repeat(context.length + (declarations ? 1 : 0));
    const body = line.slice(indent.length);
    if (line === "") {
      if (declarations || selectors.length > 0)
        throw new Error(`${where}: blank line inside a rule`);
      continue;
    }
    if (declarations && line === `${"  ".repeat(context.length)}}`) {
      blocks.push({ context: [...context], selectors, declarations });
      selectors = [];
      declarations = undefined;
      continue;
    }
    if (
      !declarations &&
      selectors.length === 0 &&
      context.length > 0 &&
      line === `${"  ".repeat(context.length - 1)}}`
    ) {
      context.pop();
      continue;
    }
    if (!line.startsWith(indent) || body.startsWith(" "))
      throw new Error(`${where}: bad indentation`);
    if (declarations) {
      const match = /^(--idg-[a-z0-9-]+|color-scheme): (.+);$/.exec(body);
      if (!match?.[1] || match[2] === undefined) throw new Error(`${where}: not a declaration`);
      checkDeclaration(match[1], match[2], where);
      declarations.push([match[1], match[2]]);
      continue;
    }
    if (AT_RULES.includes(body) && selectors.length === 0) {
      context.push(body.slice(0, -2));
      continue;
    }
    const selector = /^(.+?)( \{|,)$/.exec(body);
    if (!selector?.[1] || !allowedSelectors.includes(selector[1])) {
      throw new Error(`${where}: unexpected line ${JSON.stringify(line.slice(0, 80))}`);
    }
    selectors.push(selector[1]);
    if (selector[2] === " {") declarations = [];
  }
  if (context.length > 0 || declarations || selectors.length > 0) throw new Error("unclosed block");
  return blocks;
}
