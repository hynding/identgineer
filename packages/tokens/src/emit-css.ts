import type { ResolvedToken } from "./token-types.ts";
import { isGradientStopArray, isNumberArray, isStringArray } from "./token-types.ts";

const PREFIX = "--idg-";
const GRADIENT_ANGLE = "135deg";
const GENERATED_MARKER = "/* Generated by @identgineer/tokens. Do not edit. */";
export const LAYER_ORDER =
  "@layer idg.tokens, idg.theme, idg.design, idg.layout, idg.ux, idg.preferences;";

export function toCssVariableName(path: string): string {
  return `${PREFIX}${path.replaceAll(".", "-")}`;
}

// A quoted font name is the one place free text reaches the stylesheet, so anything that
// could close the string and start a new declaration is refused rather than escaped.
const UNSAFE_FONT_NAME = /["\\\n\r\f]/;

function formatFontFamily(token: ResolvedToken, names: readonly string[]): string {
  const plain = /^[A-Za-z0-9_-]+$/;
  return names
    .map((name) => {
      if (UNSAFE_FONT_NAME.test(name)) {
        throw new Error(`${token.source}: token "${token.path}" has an unsafe font name`);
      }
      return plain.test(name) ? name : `"${name}"`;
    })
    .join(", ");
}

function formatPercent(position: number): string {
  return `${String(Number((position * 100).toFixed(2)))}%`;
}

export function formatValue(token: ResolvedToken): string {
  const { value } = token;
  if (token.type === "fontFamily" && isStringArray(value)) return formatFontFamily(token, value);
  if (token.type === "cubicBezier" && isNumberArray(value)) {
    return `cubic-bezier(${value.join(", ")})`;
  }
  if (token.type === "gradient" && isGradientStopArray(value)) {
    const stops = value.map((stop) => `${stop.color} ${formatPercent(stop.position)}`);
    return `linear-gradient(${GRADIENT_ANGLE}, ${stops.join(", ")})`;
  }
  if (typeof value === "string" || typeof value === "number") return String(value);
  throw new Error(`${token.source}: token "${token.path}" cannot be written as ${token.type}`);
}

function declarationsFor(tokens: readonly ResolvedToken[]): string[] {
  const owners = new Map<string, string>();
  return tokens.map((token) => {
    const name = toCssVariableName(token.path);
    const previous = owners.get(name);
    if (previous !== undefined) {
      throw new Error(
        `${token.source}: tokens "${previous}" and "${token.path}" both map to ${name}`,
      );
    }
    owners.set(name, token.path);
    return `${name}: ${formatValue(token)};`;
  });
}

/** A rule of custom properties, indented to `depth`; `leading` lines come before the declarations. */
export function emitDeclarationRule(
  selectors: readonly string[],
  tokens: readonly ResolvedToken[],
  depth: number,
  leading: readonly string[] = [],
): string {
  const indent = "  ".repeat(depth);
  const lines = [
    `${indent}${selectors.join(`,\n${indent}`)} {`,
    ...[...leading, ...declarationsFor(tokens)].map((line) => `${indent}  ${line}`),
    `${indent}}`,
  ];
  return lines.join("\n");
}

function emitRule(
  selectors: readonly string[],
  scheme: string,
  tokens: readonly ResolvedToken[],
  depth: number,
): string {
  return emitDeclarationRule(selectors, tokens, depth, [`color-scheme: ${scheme};`]);
}

/** Theme-independent tokens, with a neutral light fallback for colour. */
export function emitBaseCss(tokens: readonly ResolvedToken[]): string {
  return `@layer idg.tokens {\n${emitRule([":root"], "light", tokens, 1)}\n}\n`;
}

export interface ThemeCssInput {
  readonly id: string;
  /** The default theme also answers to a bare `:root`, at zero specificity. */
  readonly isDefault: boolean;
  readonly light: readonly ResolvedToken[];
  readonly dark: readonly ResolvedToken[];
}

export function emitThemeCss({ id, isDefault, light, dark }: ThemeCssInput): string {
  const themed = `[data-theme="${id}"]`;
  const lightSelectors = isDefault ? [":where(:root)", themed] : [themed];
  const darkSelectors = [
    `${themed}[data-scheme="dark"]`,
    ...(isDefault ? [`:root:not([data-theme])[data-scheme="dark"]`] : []),
  ];
  const systemDarkSelectors = [
    `${themed}:not([data-scheme="light"])`,
    ...(isDefault ? [`:root:not([data-theme]):not([data-scheme="light"])`] : []),
  ];
  return [
    "@layer idg.theme {",
    emitRule(lightSelectors, "light", light, 1),
    "",
    emitRule(darkSelectors, "dark", dark, 1),
    "",
    "  @media (prefers-color-scheme: dark) {",
    emitRule(systemDarkSelectors, "dark", dark, 2),
    "  }",
    "}",
    "",
  ].join("\n");
}

/** Prepends the generated marker and the cascade layer order to one or more bodies. */
export function emitStylesheet(...bodies: readonly string[]): string {
  return `${GENERATED_MARKER}\n${LAYER_ORDER}\n\n${bodies.join("\n")}`;
}
