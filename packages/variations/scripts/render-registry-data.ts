import {
  DEFAULT_DESIGN_ID,
  DEFAULT_LAYOUT_ID,
  DEFAULT_THEME_ID,
  DEFAULT_UX_MODE_ID,
  DESIGNS,
  LAYOUTS,
  SCHEMES,
  THEMES,
  UX_MODES,
} from "@identgineer/tokens";
import type { ModeDefinition } from "@identgineer/tokens";
import { format, resolveConfig } from "prettier";
import { toFilePath } from "./to-file-path.ts";

const HEADER = `// Generated by \`pnpm --filter @identgineer/variations generate\`. Do not edit.
// Source: the registries of @identgineer/tokens. A test regenerates this file in memory and
// compares it byte for byte, so it cannot drift. It exists so the browser entry never imports
// the token pipeline.
`;

function textAxis<Id extends string>(
  attribute: string,
  defaultId: Id,
  modes: readonly ModeDefinition<Id>[],
): object {
  return {
    attribute,
    defaultId,
    variations: modes.map(({ id, label, description }) => ({ id, label, description })),
  };
}

function registryData(): object {
  return {
    theme: {
      attribute: "data-theme",
      defaultId: DEFAULT_THEME_ID,
      variations: THEMES.map(({ id, label, description, swatches, fonts }) => ({
        id,
        label,
        description,
        swatches,
        fonts,
      })),
    },
    design: textAxis("data-design", DEFAULT_DESIGN_ID, DESIGNS),
    layout: textAxis("data-layout", DEFAULT_LAYOUT_ID, LAYOUTS),
    ux: textAxis("data-ux", DEFAULT_UX_MODE_ID, UX_MODES),
    scheme: { attribute: "data-scheme", defaultId: "system", ids: [...SCHEMES, "system"] },
  };
}

/** Formatted with the repository's Prettier config, so `format:check` accepts the output as is. */
export async function renderRegistryData(): Promise<string> {
  const source = `${HEADER}\nexport const REGISTRY_DATA = ${JSON.stringify(registryData())} as const;\n`;
  const file = new URL("../src/generated/registry-data.ts", import.meta.url);
  const path = toFilePath(file);
  const config = await resolveConfig(path);
  return format(source, { ...config, parser: "typescript", filepath: path });
}
